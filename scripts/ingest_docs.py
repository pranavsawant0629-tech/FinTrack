import sys
import json
import time
from pathlib import Path

BASE_DIR = Path(__file__).resolve().parent.parent
if str(BASE_DIR) not in sys.path:
    sys.path.insert(0, str(BASE_DIR))

import httpx

from config.settings import settings
from app.rag.document_parser import DocumentParser
from app.rag.chunking import TextChunker
from app.rag.embeddings import embedding_manager
from app.rag.vector_store import vector_store

DATA_DIR = BASE_DIR / "data"
RAW_DIR = DATA_DIR / "raw"
QUARANTINE_DIR = DATA_DIR / "quarantine"
MANIFEST_FILE = DATA_DIR / "manifest.json"


def download_if_missing(manifest: list[dict]) -> tuple[list[str], list[str]]:
    RAW_DIR.mkdir(parents=True, exist_ok=True)
    client = httpx.Client(verify=False, follow_redirects=True, headers={"User-Agent": "Mozilla/5.0"}, timeout=60.0)

    downloaded = []
    cached = []

    for item in manifest:
        filename = item["filename"]
        target_path = RAW_DIR / filename
        if not target_path.exists():
            print(f"Downloading [{filename}] from {item['url']}...")
            try:
                resp = client.get(item["url"])
                resp.raise_for_status()
                with open(target_path, "wb") as f:
                    f.write(resp.content)
                print(f"  -> Saved {len(resp.content)} bytes to {target_path.name}")
                downloaded.append(filename)
            except Exception as e:
                print(f"  -> Error downloading {filename}: {e}")
        else:
            cached.append(filename)
            print(f"Found local cache for [{filename}] ({target_path.stat().st_size} bytes)")

    return downloaded, cached


def run_ingestion(recreate_collection: bool = True) -> dict:
    start_time = time.time()
    print("=" * 60)
    print("FINOVA AI — RAG KNOWLEDGE INGESTION PIPELINE (PHASE 2)")
    print("=" * 60)

    if not MANIFEST_FILE.exists():
        raise FileNotFoundError(f"Manifest file not found at {MANIFEST_FILE}")

    with open(MANIFEST_FILE, "r", encoding="utf-8") as f:
        manifest = json.load(f)

    print(f"Loaded manifest with {len(manifest)} document definitions.")

    # 1. Acquire / verify raw files
    downloaded_files, cached_files = download_if_missing(manifest)

    # 2. Initialize Qdrant collection with dynamic dimension
    vector_dim = embedding_manager.dimension
    print(f"\nInitializing Qdrant collection '{vector_store.collection_name}' with vector dimension {vector_dim} (recreate={recreate_collection})...")
    vector_store.ensure_collection(vector_size=vector_dim, recreate=recreate_collection)

    parser = DocumentParser()
    chunker = TextChunker(chunk_size=settings.chunk_size, chunk_overlap=settings.chunk_overlap)

    accepted_docs = []
    rejected_docs = []
    skipped_docs = []
    indexed_docs = []
    total_chunks_processed = 0

    print("\nProcessing and indexing documents...")
    for item in manifest:
        file_path = RAW_DIR / item["filename"]
        if not file_path.exists():
            print(f"Skipping missing file: {file_path.name}")
            skipped_docs.append({"filename": item["filename"], "reason": "File does not exist in data/raw/"})
            continue

        print(f"\nProcessing: {item['title']} ({item['filename']})")
        try:
            parsed_doc = parser.parse_file(file_path, extra_metadata=item)
        except Exception as exc:
            print(f"  [ERROR] Parsing failed for {item['filename']}: {exc}")
            rejected_docs.append({"filename": item["filename"], "reason": f"Parse exception: {exc}"})
            continue

        extracted_chars = len(parsed_doc.full_text.strip())
        print(f"  Pages extracted: {len(parsed_doc.pages)} | Characters: {extracted_chars}")

        # Ingestion quality guardrail: reject empty or suspiciously short documents
        if extracted_chars < 100:
            print(f"  [REJECTION] Document '{item['filename']}' has only {extracted_chars} characters. Quarantining.")
            rejected_docs.append({
                "filename": item["filename"],
                "reason": f"Insufficient extractable text ({extracted_chars} chars, minimum 100 required)",
            })
            continue

        if parsed_doc.metadata.get("has_corruption_warning"):
            print(f"  [SAFEGUARD WARNING] Document '{item['filename']}' exhibits high unusual character ratios (potential font corruption).")

        chunks = chunker.chunk_document(parsed_doc)
        print(f"  Chunks created: {len(chunks)}")

        if not chunks:
            print("  Warning: No chunks produced, skipping indexing.")
            rejected_docs.append({"filename": item["filename"], "reason": "No chunks generated by chunker"})
            continue

        chunk_texts = [c.text for c in chunks]
        embeddings = embedding_manager.embed_documents(chunk_texts)

        upserted = vector_store.upsert_chunks(chunks, embeddings)
        print(f"  Successfully indexed {upserted} chunks into Qdrant.")

        accepted_docs.append(item["filename"])
        total_chunks_processed += len(chunks)
        indexed_docs.append({
            "title": item["title"],
            "filename": item["filename"],
            "doc_id": item["doc_id"],
            "source": item.get("source", "Unknown"),
            "chunks": len(chunks),
            "topic": item["topic"],
            "pages": len(parsed_doc.pages),
            "characters": extracted_chars,
        })

    elapsed = time.time() - start_time
    total_in_store = vector_store.count()

    print("\n" + "=" * 60)
    print("INGESTION AUDIT SUMMARY")
    print("=" * 60)
    print(f"Total manifest definitions: {len(manifest)}")
    print(f"Downloaded new: {len(downloaded_files)}")
    print(f"Cached locally: {len(cached_files)}")
    print(f"Accepted & indexed: {len(accepted_docs)}")
    print(f"Rejected / quarantined: {len(rejected_docs)}")
    print(f"Skipped (missing): {len(skipped_docs)}")
    print(f"Total chunks stored: {total_chunks_processed}")
    print(f"Verified count in Qdrant: {total_in_store}")
    print(f"Time elapsed: {elapsed:.2f} seconds")

    audit_report = {
        "status": "success",
        "manifest_count": len(manifest),
        "downloaded_count": len(downloaded_files),
        "cached_count": len(cached_files),
        "accepted_count": len(accepted_docs),
        "rejected_count": len(rejected_docs),
        "skipped_count": len(skipped_docs),
        "total_chunks_stored": total_chunks_processed,
        "qdrant_total_count": total_in_store,
        "elapsed_seconds": round(elapsed, 2),
        "accepted_documents": indexed_docs,
        "rejected_documents": rejected_docs,
        "skipped_documents": skipped_docs,
    }

    # Save auditable ingestion report
    report_file = DATA_DIR / "ingestion_report.json"
    with open(report_file, "w", encoding="utf-8") as f:
        json.dump(audit_report, f, indent=2)
    print(f"Auditable ingestion report saved to: {report_file}")

    return audit_report


if __name__ == "__main__":
    run_ingestion()
